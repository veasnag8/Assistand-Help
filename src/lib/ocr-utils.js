export function formatFileSize(bytes) {
  if (!bytes) return "0 KB";
  if (bytes < 1024 * 1024) return `${Math.max(1, Math.round(bytes / 1024))} KB`;
  return `${(bytes / 1024 / 1024).toFixed(2)} MB`;
}

export function getBaseName(fileName) {
  return (fileName || "scan").replace(/\.[^.]+$/, "") || "scan";
}

export function getOcrLanguages(language, customLanguage) {
  const value = language === "custom" ? customLanguage : language;
  const languages = value
    .split(/[\s,+]+/)
    .map((item) => item.trim().toLowerCase())
    .filter(Boolean);

  return languages.length ? languages.join("+") : "eng";
}

export function getOcrProgressMessage(message) {
  const statusText = (message?.status || "Scanning text").replace(/_/g, " ");

  if (typeof message?.progress !== "number") {
    return statusText;
  }

  return `${statusText} ${Math.round(message.progress * 100)}%`;
}

export function isSupportedImageFile(file) {
  if (!file) return false;
  return (
    file.type.startsWith("image/") ||
    /\.(png|jpe?g|webp|bmp|gif|tiff?)$/i.test(file.name)
  );
}

export function isSupportedScanFile(file) {
  if (!file) return false;
  return isSupportedImageFile(file) || file.type === "application/pdf" || /\.pdf$/i.test(file.name);
}

function getImageExtension(mimeType) {
  if (mimeType === "image/jpeg") return "jpg";
  if (mimeType === "image/webp") return "webp";
  return "png";
}

export function getClipboardImageFile(clipboardData) {
  const items = Array.from(clipboardData?.items || []);
  const imageItem = items.find(
    (item) => item.kind === "file" && item.type.startsWith("image/"),
  );
  const clipboardFile = imageItem?.getAsFile();
  const file =
    clipboardFile ||
    Array.from(clipboardData?.files || []).find((item) => isSupportedImageFile(item));

  if (!file) {
    return null;
  }

  const type = file.type || "image/png";
  const name =
    file.name ||
    `pasted-image-${new Date().toISOString().replace(/[:.]/g, "-")}.${getImageExtension(type)}`;

  return new File([file], name, {
    lastModified: Date.now(),
    type,
  });
}
